//! Reading `vulkan_core.h`, so our reading of the registry can be checked
//! against Khronos's own.
//!
//! # Why this exists
//!
//! `security-model.md` R8 is the only risk in this project that has actually
//! fired, and it fired twice. Both instances have the same shape: a **wrong
//! answer that looks right**, because every check we had was symmetric.
//!
//! - `vk-parse`'s `EnumSpec::Offset` carries `dir` as *positive* rather than as
//!   "is negative", so the obvious reading inverts the sign of every
//!   extension-introduced enum value. Both sides of the round-trip agreed on the
//!   wrong number.
//! - `vulkan-headers 1.4.350` chains each core version through
//!   `apitype="internal"` sub-features, so `<feature name="VK_VERSION_1_0">`
//!   contains no commands at all and the Zink profile silently resolved to 55
//!   commands rather than 239.
//!
//! The existing defences do not reach either one. The generated round-trips are
//! symmetric by construction. The Venus differential (`crate::venus`) compares
//! member sequence, kind and width over 208 shared structs, and constants are
//! none of those — the first bug lived in exactly the gap it leaves.
//!
//! # Why the published header, rather than `vulkan_object.py`
//!
//! design.md §7.1 names Khronos's `vulkan_object.py` / `reg.py` as the
//! independent model, and states the objection to it in the same breath: a
//! checked-in fixture makes the protocol a function of an artefact that can
//! drift from `$VK_XML`.
//!
//! `vulkan_core.h` is a strictly better answer to the same question, on four
//! counts:
//!
//! 1. **It is generated by the same machinery** — `genvk.py` over `reg.py`,
//!    which is what `vulkan_object.py` is a view onto — from the same registry,
//!    by code that is not ours. Disagreeing with it means one of the two
//!    readings of `vk.xml` is wrong.
//! 2. **It cannot drift, and needs no fixture.** It ships in the *same nix store
//!    path* as `vk.xml`: `$VK_XML` is
//!    `…-vulkan-headers-1.4.350.0/share/vulkan/registry/vk.xml` and the header is
//!    `…-vulkan-headers-1.4.350.0/include/vulkan/vulkan_core.h`. [`header_path`]
//!    derives one from the other and refuses a mismatch, so the two artefacts are
//!    the same release by construction rather than by a hash somebody has to
//!    remember to update.
//! 3. **No Python in the build.** §7.1's second objection — "a Python step in the
//!    middle of a build the dev shell otherwise keeps to one toolchain" — does
//!    not arise.
//! 4. **It is the artefact the numbers are published in.** Instance 1 was caught
//!    by hand-comparing three constants against `vulkan_core.h`; this is that
//!    check, done exhaustively rather than three times.
//!
//! # What this file is, and is not
//!
//! It is a deliberately small, deliberately *separate* reader for the subset of C
//! that `vulkan_core.h` is written in. In particular it does **not** call
//! `vk_registry::Declarator`: that parser is one of the things being checked, and
//! a check that shares its parser with the thing it checks proves nothing —
//! which is R8's whole point. [`HeaderDecl::parse`] is a second, independent
//! implementation of the same tiny grammar, written by a different route (strip
//! and split, rather than tokenize and consume).
//!
//! What it cannot see: anything the header does not say. The header carries no
//! `len=`, so it cannot distinguish a pointer to one value from a pointer to an
//! array — that distinction is the Venus differential's job, and the two checks
//! are complements rather than substitutes.
//!
//! # Licence
//!
//! `vulkan_core.h` is Khronos's, Apache-2.0, and is read as *data* from the nix
//! store at test time. Nothing from it is compiled or vendored. See
//! `THIRD-PARTY.md`.

use anyhow::{Context, Result, bail};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

/// Locate `vulkan_core.h` in the same package as `$VK_XML`.
///
/// Derived from the registry path rather than from `$VULKAN_SDK`, because the
/// whole argument for this cross-check is that the two artefacts describe the
/// same release. A header from somewhere else would be a fixture that can drift,
/// which is precisely what design.md §7.1 objects to.
pub fn header_path() -> Result<PathBuf> {
    let xml = vk_registry::registry_path()?;
    // …/share/vulkan/registry/vk.xml → …/include/vulkan/vulkan_core.h
    let prefix = xml
        .parent()
        .and_then(Path::parent)
        .and_then(Path::parent)
        .and_then(Path::parent)
        .with_context(|| format!("VK_XML {} is not inside a package prefix", xml.display()))?;
    let header = prefix.join("include/vulkan/vulkan_core.h");
    if !header.is_file() {
        bail!(
            "no vulkan_core.h next to the pinned registry: expected {} beside {}. \
             The cross-check compares our reading of vk.xml against Khronos's own \
             generated header from the *same* package; a header from anywhere else \
             would be a fixture that can drift from $VK_XML.",
            header.display(),
            xml.display()
        );
    }
    Ok(header)
}

/// Every generated header of the pinned package that this comparison reads.
///
/// `vulkan_beta.h` is included, and it earns its place: the provisional
/// extensions publish API constants (`VK_SHADER_INDEX_UNUSED_AMDX`) that
/// `vk.xml` puts in `<enums name="API Constants">` alongside the rest, so our
/// model carries them. Reading only `vulkan_core.h` would make those three
/// constants *unchecked* rather than *checked and equal* — and "not compared"
/// quietly filed under "agreed" is the failure mode this whole exercise exists
/// to prevent. The platform headers (`vulkan_win32.h` and friends) are not read:
/// nothing in any profile reaches a platform type, and `plan::build` refuses one
/// outright.
pub fn header_paths() -> Result<Vec<PathBuf>> {
    let core = header_path()?;
    let mut out = vec![core.clone()];
    // `vulkan_core.h` is not the whole of the published API. Anything behind a
    // `VK_USE_PLATFORM_*` guard lives in its own header, and a profile that
    // names such an extension would otherwise be reported as inventing it —
    // which is what `VK_KHR_xcb_surface` did the first time design.md §10 stage
    // 2 put it in the profile: "the profile lists it, but vulkan_core.h has no
    // block for it". The published header exists; it is just a different file.
    //
    // Only the platform headers this project's profiles can reach are listed,
    // and each is optional, because a header set for a different release may not
    // carry all of them.
    for sibling in ["vulkan_beta.h", "vulkan_xcb.h", "vulkan_xlib.h"] {
        let p = core.with_file_name(sibling);
        if p.is_file() {
            out.push(p);
        }
    }
    out.extend(video_header_paths()?);
    Ok(out)
}

/// The `vk_video/*.h` headers of the same package.
///
/// # Why these are read at all
///
/// `vk_registry::video_registry_path` explains why the generator's *input* for
/// the `StdVideo*` types is `video.xml` rather than these headers: it is the
/// machine-readable source they are generated from, it is in the same schema as
/// `vk.xml`, and using it puts no second reader of C into the build.
///
/// That decision is only safe if the two are checked against each other, and
/// this is the file that can do it. The relationship is exactly the one this
/// module already has to `vulkan_core.h`: **the header is the published
/// artefact, and disagreeing with it means one of the two readings is wrong.**
/// Our model says `StdVideoH264SequenceParameterSet.level_idc` is a
/// `StdVideoH264LevelIdc` at member index 2 and that
/// `StdVideoH264SpsFlags.frame_mbs_only_flag` is one bit at offset 8; the header
/// says so independently, in C, and the comparison is what makes the merge
/// something other than a claim.
///
/// Every header the package ships is read, not only H.264 — including the encode
/// and AV1/VP9/H.265 ones nothing generates for yet — because the model carries
/// all of them the moment `video.xml` is merged, and a type that is *carried and
/// not compared* is the quiet case this whole exercise exists to prevent.
pub fn video_header_paths() -> Result<Vec<PathBuf>> {
    let xml = vk_registry::registry_path()?;
    // …/share/vulkan/registry/vk.xml → …/include/vk_video/
    let prefix = xml
        .parent()
        .and_then(Path::parent)
        .and_then(Path::parent)
        .and_then(Path::parent)
        .with_context(|| format!("VK_XML {} is not inside a package prefix", xml.display()))?;
    let dir = prefix.join("include/vk_video");
    if !dir.is_dir() {
        bail!(
            "no vk_video headers next to the pinned registry: expected {} beside {}. \
             video.xml defines the StdVideo* types and these headers are the only \
             independent check that our reading of it is right.",
            dir.display(),
            xml.display()
        );
    }
    let mut out = Vec::new();
    for entry in std::fs::read_dir(&dir).with_context(|| format!("reading {}", dir.display()))? {
        let p = entry?.path();
        if p.extension().is_some_and(|e| e == "h") {
            out.push(p);
        }
    }
    // `read_dir` order is the filesystem's, and a comparison whose output depends
    // on it cannot be diffed.
    out.sort();
    if out.is_empty() {
        bail!("{} contains no headers", dir.display());
    }
    Ok(out)
}

/// `VK_HEADER_VERSION` as the *registry* states it, read straight out of the XML
/// text.
///
/// Read as text, and not through `vk-parse`, on purpose: this is the provenance
/// assertion that the header and the registry are the same release, so it must
/// not go through the parser whose reading is under test.
pub fn registry_header_version(xml_text: &str) -> Option<u32> {
    let at = xml_text.find("<name>VK_HEADER_VERSION</name>")?;
    let rest = &xml_text[at + "<name>VK_HEADER_VERSION</name>".len()..];
    let digits: String = rest.trim_start().chars().take_while(|c| c.is_ascii_digit()).collect();
    digits.parse().ok()
}

/// One value of a C enum, or one 64-bit flag bit.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum HeaderEnumValue {
    Int(i64),
    /// `VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_FEATURES_2_KHR = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_FEATURES_2`
    Alias(String),
}

#[derive(Debug, Clone, Default)]
pub struct HeaderEnum {
    pub name: String,
    /// 32 for a C enum, 64 for the `static const VkFlags64` families.
    pub bit_width: u32,
    /// In declaration order.
    pub values: Vec<(String, HeaderEnumValue)>,
}

impl HeaderEnum {
    /// The number a name denotes, following the header's own alias chains.
    pub fn value(&self, name: &str) -> Option<i64> {
        let mut cur = name;
        for _ in 0..8 {
            let (_, v) = self.values.iter().find(|(n, _)| n == cur)?;
            match v {
                HeaderEnumValue::Int(i) => return Some(*i),
                HeaderEnumValue::Alias(t) => cur = t,
            }
        }
        None
    }
}

/// One declaration: a struct member or a command parameter.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct HeaderDecl {
    pub name: String,
    /// The base type, with every `*`, `const` and array extent stripped:
    /// `uint32_t`, `VkStructureType`, `void`, `char`.
    pub base_type: String,
    pub pointer_depth: usize,
    /// Array extents, outermost first, as written: `4`, `VK_UUID_SIZE`.
    pub arrays: Vec<String>,
    pub bitfield: Option<u32>,
}

impl HeaderDecl {
    /// Parse one C declaration.
    ///
    /// Deliberately *not* `vk_registry::Declarator::parse`: see the module
    /// documentation. The grammar accepted here is
    /// `const? struct? name (*|const)* name ([extent])* (: bits)?`, which is
    /// everything `vulkan_core.h` writes.
    pub fn parse(input: &str) -> Option<HeaderDecl> {
        let mut text = input.trim().trim_end_matches(';').trim().to_string();

        // Bitfield first: `uint32_t mask:8`.
        let mut bitfield = None;
        if let Some((head, bits)) = text.rsplit_once(':') {
            let bits = bits.trim();
            if bits.chars().all(|c| c.is_ascii_digit()) && !bits.is_empty() {
                bitfield = bits.parse::<u32>().ok();
                text = head.trim().to_string();
            }
        }

        // Array extents, outermost first.
        let mut arrays = Vec::new();
        while let Some(open) = text.rfind('[') {
            let close = text[open..].find(']')? + open;
            arrays.push(text[open + 1..close].trim().to_string());
            text = format!("{}{}", &text[..open], &text[close + 1..]).trim().to_string();
        }
        arrays.reverse();

        // Stars anywhere, then words.
        let pointer_depth = text.matches('*').count();
        let text = text.replace('*', " ");
        let words: Vec<&str> = text
            .split_whitespace()
            .filter(|w| *w != "const" && *w != "struct")
            .collect();
        if words.len() != 2 {
            return None;
        }
        Some(HeaderDecl {
            name: words[1].to_string(),
            base_type: words[0].to_string(),
            pointer_depth,
            arrays,
            bitfield,
        })
    }
}

#[derive(Debug, Clone, Default)]
pub struct HeaderStruct {
    pub name: String,
    pub is_union: bool,
    pub members: Vec<HeaderDecl>,
}

#[derive(Debug, Clone, Default)]
pub struct HeaderCommand {
    pub name: String,
    pub return_type: String,
    /// `*` count on the return type: `void*` for `vkGetInstanceProcAddr`.
    pub return_pointer_depth: usize,
    pub params: Vec<HeaderDecl>,
    /// The `#define VK_…  1` block the declaration appeared in.
    pub section: String,
}

/// Everything read out of `vulkan_core.h`.
#[derive(Debug, Default)]
pub struct HeaderModel {
    pub header_version: Option<u32>,
    /// `#define VK_UUID_SIZE 16U` → `("VK_UUID_SIZE", "16U")`, object-like
    /// defines only.
    pub defines: BTreeMap<String, String>,
    pub enums: BTreeMap<String, HeaderEnum>,
    /// `typedef uint64_t VkDeviceSize;` and
    /// `typedef VkPhysicalDeviceFeatures2 VkPhysicalDeviceFeatures2KHR;` alike:
    /// the header does not distinguish "underlying type" from "alias", and the
    /// distinction is not needed to resolve either.
    pub typedefs: BTreeMap<String, String>,
    /// Handle name → dispatchable.
    pub handles: BTreeMap<String, bool>,
    pub structs: BTreeMap<String, HeaderStruct>,
    /// Commands, taken from the `PFN_vk…` typedefs, which are emitted whether or
    /// not `VK_NO_PROTOTYPES` is set.
    pub commands: BTreeMap<String, HeaderCommand>,
    /// Feature or extension name → the commands its block declares, sorted.
    ///
    /// This is the header's flattened answer to "what does `VK_VERSION_1_0`
    /// provide", which is the question the 55-vs-239 bug got wrong. The header
    /// does not emit the `apitype="internal"` sub-features at all — it writes the
    /// resolved result — so it is an answer arrived at by a different route.
    pub sections: BTreeMap<String, Vec<String>>,
}

impl HeaderModel {
    pub fn load(path: &Path) -> Result<HeaderModel> {
        HeaderModel::load_all(std::slice::from_ref(&path.to_path_buf()))
    }

    /// Read several headers of one package into one model.
    pub fn load_all(paths: &[PathBuf]) -> Result<HeaderModel> {
        let mut m = HeaderModel::default();
        for path in paths {
            let text = std::fs::read_to_string(path)
                .with_context(|| format!("reading {}", path.display()))?;
            m.parse_into(&text);
        }
        m.finish();
        Ok(m)
    }

    pub fn parse(text: &str) -> HeaderModel {
        let mut m = HeaderModel::default();
        m.parse_into(text);
        m.finish();
        m
    }

    fn finish(&mut self) {
        for v in self.sections.values_mut() {
            v.sort();
            v.dedup();
        }
    }

    fn parse_into(&mut self, text: &str) {
        let m = self;
        let lines: Vec<&str> = text.lines().collect();
        let mut section = String::new();
        let mut i = 0;

        while i < lines.len() {
            let line = lines[i];

            // -- section markers ------------------------------------------
            if let Some(name) = section_marker(line) {
                // Recorded even when the block declares no commands: plenty of
                // extensions are features and structs only, and a profile that
                // lists one must not look like a profile naming a block the
                // header has never heard of.
                m.sections.entry(name.clone()).or_default();
                section = name;
                i += 1;
                continue;
            }

            // -- object-like defines --------------------------------------
            if let Some((name, body)) = object_define(line) {
                if name == "VK_HEADER_VERSION" {
                    m.header_version = body.trim().parse().ok();
                }
                m.defines.insert(name, body);
                i += 1;
                continue;
            }

            // -- handles ---------------------------------------------------
            if let Some(name) = between(line, "VK_DEFINE_HANDLE(", ")")
                && line.starts_with("VK_DEFINE_HANDLE(")
            {
                m.handles.insert(name, true);
                i += 1;
                continue;
            }
            if let Some(name) = between(line, "VK_DEFINE_NON_DISPATCHABLE_HANDLE(", ")")
                && line.starts_with("VK_DEFINE_NON_DISPATCHABLE_HANDLE(")
            {
                m.handles.insert(name, false);
                i += 1;
                continue;
            }

            // -- enums ------------------------------------------------------
            if let Some(name) = between(line, "typedef enum ", " {")
                && line.starts_with("typedef enum ")
            {
                let mut e = HeaderEnum { name: name.clone(), bit_width: 32, values: Vec::new() };
                i += 1;
                while i < lines.len() && !lines[i].starts_with('}') {
                    if let Some((n, v)) = enum_entry(lines[i]) {
                        e.values.push((n, v));
                    }
                    i += 1;
                }
                i += 1;
                m.enums.insert(name, e);
                continue;
            }

            // -- 64-bit flag bits -------------------------------------------
            // `static const VkPipelineStageFlagBits2 VK_… = 0x…ULL;`
            if let Some((group, name, value)) = flag_bit_64(line) {
                let e = m.enums.entry(group.clone()).or_insert_with(|| HeaderEnum {
                    name: group,
                    bit_width: 64,
                    values: Vec::new(),
                });
                e.bit_width = 64;
                e.values.push((name, value));
                i += 1;
                continue;
            }

            // -- structs and unions ------------------------------------------
            if let Some((name, is_union)) = struct_head(line) {
                let mut s = HeaderStruct { name: name.clone(), is_union, members: Vec::new() };
                i += 1;
                while i < lines.len() && !lines[i].starts_with('}') {
                    let l = lines[i].trim();
                    if !l.is_empty()
                        && !l.starts_with("//")
                        && !l.starts_with('#')
                        && let Some(d) = HeaderDecl::parse(l)
                    {
                        s.members.push(d);
                    }
                    i += 1;
                }
                i += 1;
                m.structs.insert(name, s);
                continue;
            }

            // -- commands ------------------------------------------------------
            if let Some(mut c) = command_typedef(line) {
                c.section = section.clone();
                m.sections.entry(section.clone()).or_default().push(c.name.clone());
                m.commands.insert(c.name.clone(), c);
                i += 1;
                continue;
            }

            // -- plain typedefs -------------------------------------------------
            if let Some((target, alias)) = plain_typedef(line) {
                m.typedefs.insert(alias, target);
                i += 1;
                continue;
            }

            i += 1;
        }
    }

    /// Resolve a type name through the header's own typedefs to the thing it
    /// ultimately is.
    pub fn resolve(&self, name: &str) -> String {
        let mut cur = name.to_string();
        for _ in 0..16 {
            match self.typedefs.get(&cur) {
                Some(next) if next != &cur => cur = next.clone(),
                _ => break,
            }
        }
        cur
    }

    /// The width in bytes the header gives a type, for an LP64 target.
    ///
    /// `None` for structs, unions and anything this cannot decide, which the
    /// comparison then skips rather than guesses at.
    pub fn width_of(&self, name: &str) -> Option<usize> {
        let base = self.resolve(name);
        Some(match base.as_str() {
            "char" | "int8_t" | "uint8_t" => 1,
            "int16_t" | "uint16_t" => 2,
            "int" | "int32_t" | "uint32_t" | "float" => 4,
            "int64_t" | "uint64_t" | "double" | "size_t" => 8,
            _ => {
                if self.enums.contains_key(&base) {
                    // A C enum is an `int` here: every Vulkan enum carries a
                    // `…_MAX_ENUM = 0x7FFFFFFF` member precisely to pin that.
                    return Some(if self.enums[&base].bit_width == 64 { 8 } else { 4 });
                }
                if self.handles.contains_key(&base) {
                    // Dispatchable handles are pointers, non-dispatchable ones
                    // `uint64_t`; on the target this project builds for, both are
                    // eight bytes.
                    return Some(8);
                }
                return None;
            }
        })
    }

    /// The numeric value of an object-like `#define`, for the ones that are
    /// numbers. `(~0U)` and `1000.0F` deliberately stay `None`.
    pub fn define_value(&self, name: &str) -> Option<u64> {
        parse_c_number(self.defines.get(name)?)
    }
}

