/// `#define VK_VERSION_1_0 1` / `#define VK_KHR_surface 1` open a feature or
/// extension block; `#define VK_KHR_SURFACE_SPEC_VERSION 1` does not.
///
/// The rule is spelled out rather than looked up in our own model on purpose:
/// deriving the section names from the registry would put our reading of the
/// registry on both sides of the comparison.
fn section_marker(line: &str) -> Option<String> {
    let rest = line.strip_prefix("#define ")?;
    let (name, value) = rest.split_once(' ')?;
    if value.trim() != "1" || !name.starts_with("VK_") {
        return None;
    }
    let tail = &name[3..];
    // A core version, or an extension name — whose vendor-suffixed tail always
    // contains a lower-case letter (`VK_KHR_surface`), unlike the all-caps
    // `…_SPEC_VERSION` and `…_EXTENSION_NAME` defines that follow it.
    if name.starts_with("VK_VERSION_") || tail.chars().any(|c| c.is_ascii_lowercase()) {
        Some(name.to_string())
    } else {
        None
    }
}

fn object_define(line: &str) -> Option<(String, String)> {
    let rest = line.strip_prefix("#define ")?;
    let (name, body) = rest.split_once(char::is_whitespace)?;
    // Function-like macros are not constants. `STD_VIDEO_` is the video std
    // headers' prefix for the same thing `VK_` is in `vulkan_core.h`: every one
    // of them is an array extent of a `StdVideo*` struct.
    if name.contains('(') || !(name.starts_with("VK_") || name.starts_with("STD_VIDEO_")) {
        return None;
    }
    let body = body.split("//").next().unwrap_or(body).trim();
    if body.is_empty() {
        return None;
    }
    Some((name.to_string(), body.to_string()))
}

fn between(line: &str, prefix: &str, suffix: &str) -> Option<String> {
    let at = line.find(prefix)? + prefix.len();
    let rest = &line[at..];
    let end = rest.find(suffix)?;
    let name = rest[..end].trim();
    if name.is_empty() || !name.chars().all(|c| c.is_alphanumeric() || c == '_') {
        return None;
    }
    Some(name.to_string())
}

/// `    VK_SUCCESS = 0,` / `    VK_X = VK_Y,`
fn enum_entry(line: &str) -> Option<(String, HeaderEnumValue)> {
    let l = line.trim().trim_end_matches(',').trim();
    let (name, value) = l.split_once('=')?;
    let name = name.trim();
    let value = value.trim();
    if name.is_empty() || !name.chars().all(|c| c.is_alphanumeric() || c == '_') {
        return None;
    }
    let v = if value.starts_with(|c: char| c.is_ascii_digit() || c == '-') {
        HeaderEnumValue::Int(parse_c_signed(value)?)
    } else if value.chars().all(|c| c.is_alphanumeric() || c == '_') {
        HeaderEnumValue::Alias(value.to_string())
    } else {
        return None;
    };
    Some((name.to_string(), v))
}

/// `static const VkPipelineStageFlagBits2 VK_PIPELINE_STAGE_2_NONE = 0ULL;`
fn flag_bit_64(line: &str) -> Option<(String, String, HeaderEnumValue)> {
    let rest = line.strip_prefix("static const ")?;
    let (group, rest) = rest.split_once(' ')?;
    let (name, value) = rest.split_once('=')?;
    let name = name.trim();
    let value = value.trim().trim_end_matches(';').trim();
    if name.is_empty() || !name.chars().all(|c| c.is_alphanumeric() || c == '_') {
        return None;
    }
    let v = if value.starts_with(|c: char| c.is_ascii_digit()) {
        HeaderEnumValue::Int(parse_c_signed(value)?)
    } else {
        HeaderEnumValue::Alias(value.to_string())
    };
    Some((group.trim().to_string(), name.to_string(), v))
}

fn struct_head(line: &str) -> Option<(String, bool)> {
    for (prefix, is_union) in [("typedef struct ", false), ("typedef union ", true)] {
        if line.starts_with(prefix)
            && line.ends_with('{')
            && let Some(name) = between(line, prefix, " {")
        {
            return Some((name, is_union));
        }
    }
    None
}

/// `typedef VkResult (VKAPI_PTR *PFN_vkCreateInstance)(const VkInstanceCreateInfo* pCreateInfo, …);`
///
/// One line only. The multi-line ones in the header are all *callback* typedefs
/// (`PFN_vkAllocationFunction`, `PFN_vkDebugUtilsMessengerCallbackEXT`), which
/// are function-pointer types rather than commands and are not serialisable
/// anyway (design.md §6.1).
fn command_typedef(line: &str) -> Option<HeaderCommand> {
    let rest = line.strip_prefix("typedef ")?;
    if !line.ends_with(");") {
        return None;
    }
    let (ret, rest) = rest.split_once("(VKAPI_PTR *PFN_")?;
    let (name, params) = rest.split_once(')')?;
    if !name.starts_with("vk") {
        return None;
    }
    let params = params.trim().strip_prefix('(')?.strip_suffix(");")?;
    let ret = ret.trim();
    let return_pointer_depth = ret.matches('*').count();
    let return_type = ret.replace('*', " ").split_whitespace().next()?.to_string();

    // `typedef void (VKAPI_PTR *PFN_vkVoidFunction)(void);` is the generic
    // entry-point type, not a command — and it is the only `PFN_vk…` in the
    // header that takes no parameters, since every real Vulkan command takes at
    // least the object it dispatches from. That is the rule used here, so the
    // classification stays a fact about the header rather than a name we had to
    // know in advance.
    if params.trim() == "void" || params.trim().is_empty() {
        return None;
    }
    let mut out = Vec::new();
    for p in params.split(',') {
        out.push(HeaderDecl::parse(p)?);
    }
    Some(HeaderCommand {
        name: name.to_string(),
        return_type,
        return_pointer_depth,
        params: out,
        section: String::new(),
    })
}

/// `typedef uint64_t VkDeviceSize;`, `typedef VkFlags VkImageUsageFlags;`,
/// `typedef VkPhysicalDeviceFeatures2 VkPhysicalDeviceFeatures2KHR;`
fn plain_typedef(line: &str) -> Option<(String, String)> {
    let rest = line.strip_prefix("typedef ")?.strip_suffix(';')?;
    if rest.contains('(') || rest.contains('*') || rest.contains('[') {
        return None;
    }
    let words: Vec<&str> = rest.split_whitespace().collect();
    if words.len() != 2 || words[0] == "struct" || words[0] == "union" || words[0] == "enum" {
        return None;
    }
    Some((words[0].to_string(), words[1].to_string()))
}

/// `256U`, `0x00000001`, `16`, `(~0U)`, `1000.0F` — numbers only, and the
/// sentinels stay `None` rather than being truncated into something plausible.
pub fn parse_c_number(text: &str) -> Option<u64> {
    let t = text.trim().trim_end_matches(['U', 'u', 'L', 'l']);
    if let Some(hex) = t.strip_prefix("0x").or_else(|| t.strip_prefix("0X")) {
        return u64::from_str_radix(hex, 16).ok();
    }
    t.parse::<u64>().ok()
}

fn parse_c_signed(text: &str) -> Option<i64> {
    let t = text.trim().trim_end_matches(['U', 'u', 'L', 'l']);
    if let Some(hex) = t.strip_prefix("0x").or_else(|| t.strip_prefix("0X")) {
        return u64::from_str_radix(hex, 16).ok().map(|v| v as i64);
    }
    t.parse::<i64>().ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn declarations_this_header_actually_writes() {
        let d = HeaderDecl::parse("    const uint32_t*        pQueueFamilyIndices;").unwrap();
        assert_eq!(d.name, "pQueueFamilyIndices");
        assert_eq!(d.base_type, "uint32_t");
        assert_eq!(d.pointer_depth, 1);

        let d = HeaderDecl::parse("    char        deviceName[VK_MAX_PHYSICAL_DEVICE_NAME_SIZE];")
            .unwrap();
        assert_eq!(d.base_type, "char");
        assert_eq!(d.arrays, vec!["VK_MAX_PHYSICAL_DEVICE_NAME_SIZE".to_string()]);

        let d = HeaderDecl::parse("    const char* const*   ppEnabledExtensionNames;").unwrap();
        assert_eq!(d.base_type, "char");
        assert_eq!(d.pointer_depth, 2);

        let d = HeaderDecl::parse("    const void* const *    pParams;").unwrap();
        assert_eq!(d.base_type, "void");
        assert_eq!(d.pointer_depth, 2);

        // `float matrix[3][4]` is three rows of four, outermost first.
        let d = HeaderDecl::parse("    float    matrix[3][4];").unwrap();
        assert_eq!(d.arrays, vec!["3".to_string(), "4".to_string()]);

        let d = HeaderDecl::parse("    uint32_t    mask:8;").unwrap();
        assert_eq!(d.bitfield, Some(8));
        assert_eq!(d.base_type, "uint32_t");
    }

    #[test]
    fn section_markers_are_not_spec_version_defines() {
        assert_eq!(section_marker("#define VK_VERSION_1_0 1").as_deref(), Some("VK_VERSION_1_0"));
        assert_eq!(section_marker("#define VK_KHR_surface 1").as_deref(), Some("VK_KHR_surface"));
        assert_eq!(section_marker("#define VK_KHR_SURFACE_SPEC_VERSION 7"), None);
        // The one that would be a false positive if the rule were "value is 1".
        assert_eq!(section_marker("#define VK_KHR_DYNAMIC_RENDERING_SPEC_VERSION 1"), None);
    }

    #[test]
    fn a_command_typedef_is_a_signature() {
        let c = command_typedef(
            "typedef VkResult (VKAPI_PTR *PFN_vkCreateInstance)(const VkInstanceCreateInfo* \
             pCreateInfo, const VkAllocationCallbacks* pAllocator, VkInstance* pInstance);",
        )
        .unwrap();
        assert_eq!(c.name, "vkCreateInstance");
        assert_eq!(c.return_type, "VkResult");
        assert_eq!(c.params.len(), 3);
        assert_eq!(c.params[2].name, "pInstance");
        assert_eq!(c.params[2].base_type, "VkInstance");
        assert_eq!(c.params[2].pointer_depth, 1);
        // A callback typedef spread over several lines is not a command.
        assert!(command_typedef("typedef void* (VKAPI_PTR *PFN_vkAllocationFunction)(").is_none());
    }

    #[test]
    fn enum_entries_and_flag_bits() {
        assert_eq!(
            enum_entry("    VK_ERROR_SURFACE_LOST_KHR = -1000000000,"),
            Some(("VK_ERROR_SURFACE_LOST_KHR".into(), HeaderEnumValue::Int(-1_000_000_000)))
        );
        assert_eq!(
            enum_entry("    VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_FEATURES_2_KHR = \
                        VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_FEATURES_2,"),
            Some((
                "VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_FEATURES_2_KHR".into(),
                HeaderEnumValue::Alias("VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_FEATURES_2".into())
            ))
        );
        let (group, name, value) =
            flag_bit_64("static const VkPipelineStageFlagBits2 VK_PIPELINE_STAGE_2_COPY_BIT = \
                         0x400000000ULL;")
                .unwrap();
        assert_eq!(group, "VkPipelineStageFlagBits2");
        assert_eq!(name, "VK_PIPELINE_STAGE_2_COPY_BIT");
        assert_eq!(value, HeaderEnumValue::Int(0x4_0000_0000));
    }

    #[test]
    fn numbers_that_are_not_numbers_stay_absent() {
        assert_eq!(parse_c_number("256U"), Some(256));
        assert_eq!(parse_c_number("0x00000010"), Some(16));
        assert_eq!(parse_c_number("(~0U)"), None);
        assert_eq!(parse_c_number("1000.0F"), None);
    }
}
