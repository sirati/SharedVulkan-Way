//! The Linux side's pure parts: what `xdg-open` and an "open with a host
//! application" desktop entry turn a target into, the desktop entries and
//! `mimeapps.list` generated from the host's handlers, and how paths map
//! between the two sides.

use std::fmt::Write;

use crate::wire::{Handler, PathMap, Req, Target};

/// The desktop entry of the host's browser: Linux's default for http, https
/// and text/html.
pub const BROWSER_ENTRY: &str = "wc-host-browser.desktop";

/// The desktop entry file name of a host handler.
pub fn handler_entry(token: &str) -> String {
    format!("wc-host-{token}.desktop")
}

/// Desktop-entry value escaping (`\s`, `\n`, `\t`, `\\`, and a `;` in a list).
fn de_value(s: &str) -> String {
    let mut o = String::new();
    for c in s.chars() {
        match c {
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            '\t' => o.push_str("\\t"),
            '\r' => o.push_str("\\r"),
            c if c.is_control() => o.push(' '),
            c => o.push(c),
        }
    }
    o
}

/// An `Exec=` argument, quoted as the desktop entry spec wants: inside
/// double quotes, `"`, `` ` ``, `$` and `\` are backslash-escaped, and the
/// value escaping applies on top.
fn exec_arg(s: &str) -> String {
    let mut q = String::from("\"");
    for c in s.chars() {
        if matches!(c, '"' | '`' | '$' | '\\') {
            q.push('\\');
        }
        q.push(c);
    }
    q.push('"');
    de_value(&q)
}

/// The browser entry. `opener` is the absolute path of `wc-host-open`.
pub fn browser_entry(opener: &str, host: &str) -> String {
    format!(
        "[Desktop Entry]\nType=Application\nName={host} browser\nComment=Opens links in the browser of the {host} desktop\n\
         Exec={} %u\nNoDisplay=true\nTerminal=false\n\
         MimeType=x-scheme-handler/http;x-scheme-handler/https;text/html;application/xhtml+xml;\n",
        exec_arg(opener)
    )
}

/// One host handler as a Linux application: "Notepad (Windows)". Its
/// `Exec=` passes only the host's token; the host maps it back to its own
/// application.
pub fn handler_desktop_entry(h: &Handler, opener: &str, host: &str) -> String {
    let mut mimes: Vec<String> = h.mimes.clone();
    for s in &h.schemes {
        mimes.push(format!("x-scheme-handler/{s}"));
    }
    let mut e = String::new();
    let _ = write!(
        e,
        "[Desktop Entry]\nType=Application\nName={} ({host})\nComment=Opens the file with {} on the {host} desktop\n\
         Exec={} --with {} %U\nTerminal=false\n",
        de_value(&h.name),
        de_value(&h.name),
        exec_arg(opener),
        h.token
    );
    if !mimes.is_empty() {
        let _ = writeln!(e, "MimeType={};", mimes.join(";"));
    }
    e
}

/// `mimeapps.list` for the session: the host's browser for the web types,
/// each type's host default as Linux's default, and every handler as an
/// added association (so it shows in "Open with").
pub fn mimeapps(handlers: &[Handler]) -> String {
    let mut defaults: Vec<(String, String)> = vec![
        ("x-scheme-handler/http".into(), BROWSER_ENTRY.into()),
        ("x-scheme-handler/https".into(), BROWSER_ENTRY.into()),
        ("text/html".into(), BROWSER_ENTRY.into()),
        ("application/xhtml+xml".into(), BROWSER_ENTRY.into()),
    ];
    for h in handlers {
        for m in &h.default_for {
            if !defaults.iter().any(|(t, _)| t == m) {
                defaults.push((m.clone(), handler_entry(&h.token)));
            }
        }
    }
    let mut added: Vec<(String, Vec<String>)> = Vec::new();
    for h in handlers {
        for m in &h.mimes {
            match added.iter_mut().find(|(t, _)| t == m) {
                Some((_, v)) => v.push(handler_entry(&h.token)),
                None => added.push((m.clone(), vec![handler_entry(&h.token)])),
            }
        }
    }
    let mut s = String::from("# Generated by wc-proxy for this session (wc-hostint). Do not edit.\n[Default Applications]\n");
    for (t, e) in &defaults {
        let _ = writeln!(s, "{t}={e}");
    }
    s.push_str("\n[Added Associations]\n");
    for (t, es) in &added {
        let _ = writeln!(s, "{t}={};", es.join(";"));
    }
    s
}

// --------------------------------------------------------------- path map --

fn is_win(p: &str) -> bool {
    let b = p.as_bytes();
    b.len() >= 2 && b[0].is_ascii_alphabetic() && b[1] == b':'
}

/// A host path as a Linux path, if it is inside a share.
pub fn host_to_linux(host: &str, map: &PathMap) -> Option<String> {
    for (h, l) in &map.shares {
        let rest = if is_win(h) {
            let hn = h.replace('/', "\\").trim_end_matches('\\').to_ascii_lowercase();
            let pn = host.replace('/', "\\");
            let low = pn.to_ascii_lowercase();
            if low == hn {
                Some(String::new())
            } else if low.starts_with(&format!("{hn}\\")) {
                Some(pn[hn.len() + 1..].replace('\\', "/"))
            } else {
                None
            }
        } else {
            let hn = h.trim_end_matches('/');
            if host == hn {
                Some(String::new())
            } else {
                host.strip_prefix(&format!("{hn}/")).map(String::from)
            }
        };
        if let Some(r) = rest {
            if r.split('/').any(|c| c == "..") {
                return None;
            }
            let l = l.trim_end_matches('/');
            return Some(if r.is_empty() { l.to_string() } else { format!("{l}/{r}") });
        }
    }
    None
}

/// A Linux path as a host path, if it is inside a share. `linux` must be
/// absolute and already resolved (no `..`, symlinks followed by the caller).
pub fn linux_to_host(linux: &str, map: &PathMap) -> Option<String> {
    if linux.split('/').any(|c| c == "..") {
        return None;
    }
    for (h, l) in &map.shares {
        let ln = l.trim_end_matches('/');
        let rest = if linux == ln { Some("") } else { linux.strip_prefix(&format!("{ln}/")) };
        if let Some(r) = rest {
            return Some(if is_win(h) {
                let hn = h.replace('/', "\\");
                let hn = hn.trim_end_matches('\\');
                if r.is_empty() { format!("{hn}\\") } else { format!("{hn}\\{}", r.replace('/', "\\")) }
            } else {
                let hn = h.trim_end_matches('/');
                if r.is_empty() { hn.to_string() } else { format!("{hn}/{r}") }
            });
        }
    }
    None
}

/// What the opener was given on its command line.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Given {
    /// A URL with a scheme other than `file`.
    Url(String),
    /// A local path, absolute and resolved (from a path or a `file:` URL).
    Path(String),
}

/// Decode a `file://` URL's path (percent-decoding; only `file:///path` or
/// `file://localhost/path`).
pub fn file_url_path(u: &str) -> Option<String> {
    let rest = u.strip_prefix("file://")?;
    let path = rest.strip_prefix("localhost").unwrap_or(rest);
    if !path.starts_with('/') {
        return None;
    }
    let b = path.as_bytes();
    let mut out = Vec::new();
    let mut i = 0;
    while i < b.len() {
        if b[i] == b'%' && i + 2 < b.len() {
            let h = std::str::from_utf8(&b[i + 1..i + 3]).ok()?;
            out.push(u8::from_str_radix(h, 16).ok()?);
            i += 3;
        } else if b[i] == b'?' || b[i] == b'#' {
            break;
        } else {
            out.push(b[i]);
            i += 1;
        }
    }
    String::from_utf8(out).ok()
}

/// Classify an argument: a `scheme:` URL (scheme per RFC 3986, at least two
/// characters so `C:` is not one), a `file:` URL, or a path.
pub fn classify(arg: &str) -> Given {
    if let Some(p) = file_url_path(arg) {
        return Given::Path(p);
    }
    if let Some((s, _)) = arg.split_once(':')
        && s.len() >= 2
            && s.starts_with(|c: char| c.is_ascii_alphabetic())
            && s.chars().all(|c| c.is_ascii_alphanumeric() || "+-.".contains(c))
        {
            return Given::Url(arg.to_string());
        }
    Given::Path(arg.to_string())
}

/// What to do with a target.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Plan {
    Send(Req),
    /// A Linux-only file that must be copied to the drop directory first
    /// (`linux_dir`, seen by the host as `host_dir`), then sent.
    CopyThenSend { from: String, linux_dir: String, host_dir: String, token: Option<String> },
    Refuse(String),
}

/// `xdg-open TARGET` (token `None`) or the handler entry's
/// `--with TOKEN TARGET`. `resolved` is the absolute, symlink-free path for a
/// path target (the caller canonicalises it; None if it does not exist).
pub fn plan(given: &Given, resolved: Option<&str>, token: Option<&str>, map: &PathMap, host: &str) -> Plan {
    match given {
        Given::Url(u) => Plan::Send(match token {
            None => Req::Url(u.clone()),
            Some(t) => Req::With { token: t.into(), target: Target::Url(u.clone()) },
        }),
        Given::Path(p) => {
            let Some(abs) = resolved else {
                return Plan::Refuse(format!("{p}: no such file"));
            };
            if let Some(h) = linux_to_host(abs, map) {
                return Plan::Send(match token {
                    None => Req::Path(h),
                    Some(t) => Req::With { token: t.into(), target: Target::HostPath(h) },
                });
            }
            let shares: Vec<&str> = map.shares.iter().map(|(_, l)| l.as_str()).collect();
            match (token, &map.drop) {
                // "Open with <host app>" on a Linux-only file: a copy goes
                // to the drop directory, and the host opens the copy.
                (Some(t), Some((hd, ld))) => Plan::CopyThenSend {
                    from: abs.into(),
                    linux_dir: ld.clone(),
                    host_dir: hd.clone(),
                    token: Some(t.into()),
                },
                _ => Plan::Refuse(format!(
                    "{abs} is not in a folder the {host} desktop can see ({}); \
                     only files there open on {host}. Move it there, or use \"Open with\" and a {host} application, \
                     which opens a copy.",
                    if shares.is_empty() { "none is shared".to_string() } else { shares.join(", ") }
                )),
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn winmap() -> PathMap {
        PathMap {
            shares: vec![("Z:\\".into(), "/srv/winshare".into())],
            drop: Some(("Z:\\waycompose-open".into(), "/srv/winshare/waycompose-open".into())),
        }
    }
    fn macmap() -> PathMap {
        PathMap { shares: vec![("/Users/alice".into(), "/Users/alice".into())], drop: Some(("/Users/alice/.waycompose-open".into(), "/Users/alice/.waycompose-open".into())) }
    }

    #[test]
    fn paths_both_ways() {
        let w = winmap();
        assert_eq!(host_to_linux("Z:\\docs\\a b.txt", &w).as_deref(), Some("/srv/winshare/docs/a b.txt"));
        assert_eq!(host_to_linux("z:/docs/a.txt", &w).as_deref(), Some("/srv/winshare/docs/a.txt"));
        assert_eq!(host_to_linux("C:\\Users\\a\\x.txt", &w), None);
        assert_eq!(host_to_linux("Z:\\..\\x", &w), None);
        assert_eq!(linux_to_host("/srv/winshare/docs/a b.txt", &w).as_deref(), Some("Z:\\docs\\a b.txt"));
        assert_eq!(linux_to_host("/srv/winshare", &w).as_deref(), Some("Z:\\"));
        assert_eq!(linux_to_host("/srv/winsharex/a", &w), None);
        assert_eq!(linux_to_host("/home/u/a.txt", &w), None);
        let m = macmap();
        assert_eq!(host_to_linux("/Users/alice/Desktop/x.html", &m).as_deref(), Some("/Users/alice/Desktop/x.html"));
        assert_eq!(linux_to_host("/Users/alice/x", &m).as_deref(), Some("/Users/alice/x"));
        assert_eq!(linux_to_host("/Users/alicex", &m), None);
    }

    #[test]
    fn file_urls() {
        assert_eq!(file_url_path("file:///srv/winshare/a%20b.txt").as_deref(), Some("/srv/winshare/a b.txt"));
        assert_eq!(file_url_path("file://localhost/x").as_deref(), Some("/x"));
        assert_eq!(file_url_path("file://otherhost/x"), None);
        assert_eq!(file_url_path("file:///a%2").as_deref(), Some("/a%2"));
        assert_eq!(file_url_path("file:///a%zz"), None);
        assert_eq!(classify("https://example.org"), Given::Url("https://example.org".into()));
        assert_eq!(classify("mailto:a@b"), Given::Url("mailto:a@b".into()));
        assert_eq!(classify("file:///tmp/x"), Given::Path("/tmp/x".into()));
        assert_eq!(classify("C:\\x"), Given::Path("C:\\x".into()));
        assert_eq!(classify("notes.txt"), Given::Path("notes.txt".into()));
    }

    #[test]
    fn plans() {
        let w = winmap();
        assert_eq!(plan(&classify("https://e.org/"), None, None, &w, "Windows"), Plan::Send(Req::Url("https://e.org/".into())));
        assert_eq!(
            plan(&Given::Path("/srv/winshare/a.txt".into()), Some("/srv/winshare/a.txt"), None, &w, "Windows"),
            Plan::Send(Req::Path("Z:\\a.txt".into()))
        );
        // xdg-open of a Linux-only file: refused, and says why.
        let Plan::Refuse(why) = plan(&Given::Path("/home/u/a.txt".into()), Some("/home/u/a.txt"), None, &w, "Windows") else { panic!() };
        assert!(why.contains("/srv/winshare") && why.contains("not in a folder"), "{why}");
        // Open with a host application: a copy.
        assert_eq!(
            plan(&Given::Path("/home/u/a.txt".into()), Some("/home/u/a.txt"), Some("n0"), &w, "Windows"),
            Plan::CopyThenSend { from: "/home/u/a.txt".into(), linux_dir: "/srv/winshare/waycompose-open".into(), host_dir: "Z:\\waycompose-open".into(), token: Some("n0".into()) }
        );
        assert!(matches!(plan(&Given::Path("x".into()), None, None, &w, "Windows"), Plan::Refuse(_)));
    }

    #[test]
    fn entries() {
        let h = Handler {
            token: "n0".into(),
            name: "Notepad".into(),
            mimes: vec!["text/plain".into()],
            default_for: vec!["text/plain".into()],
            schemes: vec![],
        };
        let e = handler_desktop_entry(&h, "/opt/wc/bin/wc-host-open", "Windows");
        assert!(e.contains("Name=Notepad (Windows)\n"));
        assert!(e.contains("Exec=\"/opt/wc/bin/wc-host-open\" --with n0 %U\n"));
        assert!(e.contains("MimeType=text/plain;\n"));
        let b = browser_entry("/a b/wc-host-open", "Windows");
        assert!(b.contains("Exec=\"/a b/wc-host-open\" %u\n"));
        let m = mimeapps(&[h]);
        assert!(m.contains("x-scheme-handler/https=wc-host-browser.desktop\n"));
        assert!(m.contains("text/plain=wc-host-n0.desktop\n"));
        assert!(m.contains("[Added Associations]\ntext/plain=wc-host-n0.desktop;\n"));
        // A hostile name cannot add a key.
        let evil = Handler { name: "X\nExec=rm -rf ~".into(), ..Handler { token: "e".into(), name: String::new(), mimes: vec![], default_for: vec![], schemes: vec![] } };
        let e = handler_desktop_entry(&evil, "/o", "Windows");
        assert_eq!(e.lines().filter(|l| l.starts_with("Exec=")).count(), 1);
        assert!(exec_arg("a$b\"c").contains("a\\\\$b\\\\\"c"));
    }
}
