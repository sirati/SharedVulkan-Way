#!/usr/bin/env bash
# Disposable profiles only. No browser is launched and no real HOME is read.
set -euo pipefail
ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
source <(sed -n '/^clear_legacy_graphics_prefs() {/,/^}/p' "$ROOT/scripts/wc-session")
source <(sed -n '/^install_managed_profile_prefs() {/,/^}/p' "$ROOT/scripts/wc-session")
STAGE=$(mktemp -d /mnt/datasets/builds/wcrun/profile-upgrade-XXXXXX)
trap 'rm -rf "$STAGE"' EXIT
mkdir -p "$STAGE/owned" "$STAGE/manual" "$STAGE/mixed" "$STAGE/partial"
cat >"$STAGE/owned/user.js" <<'JS'
// keep this user's content
user_pref("keep.user.setting", 7);
// Added by wc-session: this host forwards a GPU (/fixture/gpu.env).
user_pref("gfx.webrender.all", true);
// Added by wc-session: Vulkan video decode, read back to host memory, on the forwarded GPU.
user_pref("media.hardware-video-decoding-vulkan.enabled", true);
user_pref("media.hardware-video-decoding-vulkan.force-enabled", true);
user_pref("media.hardware-video-decoding-vulkan.readback.enabled", true);
// keep the last comment
JS
cat >"$STAGE/owned/prefs.js" <<'JS'
user_pref("gfx.webrender.all", true);
user_pref("media.hardware-video-decoding-vulkan.enabled", true);
user_pref("media.hardware-video-decoding-vulkan.force-enabled", true);
user_pref("media.hardware-video-decoding-vulkan.readback.enabled", true);
user_pref("keep.user.setting", 7);
JS
cp "$STAGE/owned/prefs.js" "$STAGE/manual/user.js"
cp "$STAGE/owned/prefs.js" "$STAGE/manual/prefs.js"
cp "$STAGE/manual/user.js" "$STAGE/manual.expected"
clear_legacy_graphics_prefs "$STAGE/owned"
cat >"$STAGE/expected-user" <<'JS'
// keep this user's content
user_pref("keep.user.setting", 7);
// keep the last comment
JS
cmp "$STAGE/expected-user" "$STAGE/owned/user.js"
printf '%s\n' 'user_pref("keep.user.setting", 7);' >"$STAGE/expected-prefs"
cmp "$STAGE/expected-prefs" "$STAGE/owned/prefs.js"
echo 'PASS removes exact generated graphics/media blocks and their persisted values'
clear_legacy_graphics_prefs "$STAGE/manual"
cmp "$STAGE/manual.expected" "$STAGE/manual/user.js"
cmp "$STAGE/manual.expected" "$STAGE/manual/prefs.js"
echo 'PASS preserves manually authored same-key preferences without provenance'
cat >"$STAGE/mixed/user.js" <<'JS'
// Added by wc-session: this host forwards a GPU (/fixture/gpu.env).
user_pref("gfx.webrender.all", true);
// User setting, not generated by the launcher.
user_pref("gfx.webrender.all", true);
JS
printf '%s\n' 'user_pref("gfx.webrender.all", true);' >"$STAGE/mixed/prefs.js"
cp "$STAGE/mixed/prefs.js" "$STAGE/mixed.expected"
clear_legacy_graphics_prefs "$STAGE/mixed"
[ "$(grep -c 'user_pref' "$STAGE/mixed/user.js")" = 1 ]
cmp "$STAGE/mixed.expected" "$STAGE/mixed/prefs.js"
echo 'PASS preserves manual same-key declaration alongside a generated block'
cat >"$STAGE/partial/user.js" <<'JS'
// Added by wc-session: this host forwards a GPU (/fixture/gpu.env).

user_pref("gfx.webrender.all", true);
// Added by wc-session: Vulkan video decode, read back to host memory, on the forwarded GPU.
user_pref("media.hardware-video-decoding-vulkan.enabled", true);
user_pref("media.hardware-video-decoding-vulkan.force-enabled", false);
user_pref("media.hardware-video-decoding-vulkan.readback.enabled", true);
JS
cp "$STAGE/partial/user.js" "$STAGE/partial.expected"
clear_legacy_graphics_prefs "$STAGE/partial"
cmp "$STAGE/partial.expected" "$STAGE/partial/user.js"
echo 'PASS preserves incomplete or edited legacy blocks'
clear_legacy_graphics_prefs "$STAGE/owned"
cmp "$STAGE/expected-user" "$STAGE/owned/user.js"
cmp "$STAGE/expected-prefs" "$STAGE/owned/prefs.js"
echo 'PASS legacy migration is idempotent'
printf '%s\n' 'user_pref("middlemouse.paste", false);' >"$STAGE/rendered"
install_managed_profile_prefs "$STAGE/manual" "$STAGE/rendered"
cat "$STAGE/manual.expected" >"$STAGE/managed.expected"
cat >>"$STAGE/managed.expected" <<'JS'
// BEGIN wc-session managed preferences
user_pref("middlemouse.paste", false);
// END wc-session managed preferences
JS
cmp "$STAGE/managed.expected" "$STAGE/manual/user.js"
install_managed_profile_prefs "$STAGE/manual" "$STAGE/rendered"
cmp "$STAGE/managed.expected" "$STAGE/manual/user.js"
echo 'PASS refreshing managed defaults preserves user content and is idempotent'
if install_managed_profile_prefs "$STAGE/manual" "$STAGE/missing-rendered" 2>/dev/null; then
  echo 'FAIL accepted missing rendered preferences'; exit 1
fi
cmp "$STAGE/managed.expected" "$STAGE/manual/user.js"
echo 'PASS failed refresh leaves the existing profile content intact'
